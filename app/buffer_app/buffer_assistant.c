static int assistant_persist(const struct disk_state_s *state,const char *event_type,
                             const struct buffer_assistant_request_s *request)
{
#ifdef CONFIG_BUFFER_VELA_SOURCE_JOURNAL
  cJSON *value=assistant_encode(state);if(!value)return -ENOMEM;
  if(request){
    cJSON *args=assistant_encode_request(request);
    if(!args){cJSON_Delete(value);return -ENOMEM;}
    if(!cJSON_ReplaceItemInObjectCaseSensitive(value,"request",args)){cJSON_Delete(args);cJSON_Delete(value);return -ENOMEM;}
  }
  int ret=buffer_source_projection_json(ASSISTANT_JOURNAL_FILE,value,event_type,NULL);
  if(ret){
    /* A failed call may already have durably accepted its WAL. Resolve that
     * intent before deciding whether the caller may adopt the new state. */
    cJSON *saved=buffer_source_projection_read(ASSISTANT_JOURNAL_FILE,BUFFER_AGENT_JSON_BYTES);
    if(saved&&cJSON_Compare(saved,value,true))ret=0;
    cJSON_Delete(saved);
    if(ret)g_storage_reconcile=true;
  }
  cJSON_Delete(value);return ret;
#else
  (void)event_type;(void)request;
  struct disk_state_s *copy = &g_persist_state;
  int fd;
  int ret;

  *copy = *state;
  copy->magic = ASSISTANT_DISK_MAGIC;
  copy->version = ASSISTANT_DISK_VERSION;
  copy->bytes = sizeof(*copy);
  copy->checksum = 0;
  copy->checksum = assistant_crc32((const unsigned char *)copy, sizeof(*copy));
  fd = open(ASSISTANT_STATE_TEMP, O_WRONLY | O_CREAT | O_TRUNC, 0600);
  if (fd < 0) return -errno;
  ret = assistant_write_all(fd, copy, sizeof(*copy));
  if (ret == 0 && fsync(fd) != 0) ret = -errno;
  if (close(fd) != 0 && ret == 0) ret = -errno;
  if (ret == 0 && rename(ASSISTANT_STATE_TEMP, ASSISTANT_STATE_FILE) != 0)
    ret = -errno;
  if (ret < 0) unlink(ASSISTANT_STATE_TEMP);
  return ret;
#endif
}

static int assistant_load_legacy(struct disk_state_s *state)
{
  unsigned char extra;
  uint32_t expected;
  memset(state, 0, sizeof(*state));
  int fd = open(ASSISTANT_STATE_FILE, O_RDONLY);
  if (fd < 0) return errno == ENOENT ? -ENOENT : -errno;

  size_t received = 0;
  while (received < sizeof(*state))
    {
      ssize_t amount = read(fd, (unsigned char *)state + received,
                            sizeof(*state) - received);
      if (amount < 0)
        {
          if (errno == EINTR) continue;
          int ret = -errno;
          close(fd);
          return ret;
        }
      if (amount == 0) break;
      received += (size_t)amount;
    }
  ssize_t tail = read(fd, &extra, 1);
  int read_error = tail < 0 ? -errno : 0;
  close(fd);
  if (read_error < 0) return read_error;
  if (received != sizeof(*state) || tail != 0 ||
      state->magic != ASSISTANT_DISK_MAGIC ||
      state->version != ASSISTANT_DISK_VERSION || state->bytes != sizeof(*state) ||
      state->timer_count > BUFFER_ASSISTANT_MAX_TIMERS ||
      state->alarm_count > BUFFER_ASSISTANT_MAX_ALARMS ||
      state->operation_count > ASSISTANT_OP_HISTORY ||
      (state->operation_next >= ASSISTANT_OP_HISTORY &&
       !(state->operation_count == ASSISTANT_OP_HISTORY && state->operation_next == ASSISTANT_OP_HISTORY)))
    return -EBADMSG;

  expected = state->checksum;
  state->checksum = 0;
  if (assistant_crc32((const unsigned char *)state, sizeof(*state)) != expected)
    return -EBADMSG;
  state->checksum = expected;

  for (size_t i = 0; i < state->timer_count; i++)
    if (memchr(state->timers[i].id, 0, sizeof(state->timers[i].id)) == NULL ||
        memchr(state->timers[i].label, 0, sizeof(state->timers[i].label)) == NULL ||
        state->timers[i].state < BUFFER_ASSISTANT_RUNNING ||
        state->timers[i].state > BUFFER_ASSISTANT_CANCELLED ||
        state->timers[i].duration_ms == 0 ||
        state->timers[i].duration_ms > ASSISTANT_MAX_TIMER_MS)
      return -EBADMSG;
  for (size_t i = 0; i < state->alarm_count; i++)
    if (memchr(state->alarms[i].id, 0, sizeof(state->alarms[i].id)) == NULL ||
        memchr(state->alarms[i].label, 0, sizeof(state->alarms[i].label)) == NULL ||
        state->alarms[i].state < BUFFER_ASSISTANT_RUNNING ||
        state->alarms[i].state > BUFFER_ASSISTANT_CANCELLED ||
        state->alarms[i].scheduled_at_unix_ms <= 0)
      return -EBADMSG;
  for (size_t i = 0; i < state->operation_count; i++)
    if (memchr(state->operations[i].operation_id, 0,
               sizeof(state->operations[i].operation_id)) == NULL ||
        memchr(state->operations[i].object_id, 0,
               sizeof(state->operations[i].object_id)) == NULL)
      return -EBADMSG;
  /* One older writer saved 32 after filling the final ring slot. The checksum
   * above must validate before normalizing that known representation. */
  if (state->operation_next == ASSISTANT_OP_HISTORY)
    {
      state->operation_next = 0;
      state->checksum = 0;
      state->checksum = assistant_crc32((const unsigned char *)state, sizeof(*state));
    }
  return 0;
}

static bool assistant_valid_text(const char *text, size_t capacity,
                                 bool allow_empty)
{
  if (text == NULL || memchr(text, 0, capacity) == NULL) return false;
  if (!allow_empty && text[0] == 0) return false;
  for (const unsigned char *p = (const unsigned char *)text; *p; p++)
    if (*p < 0x20 && *p != '\n' && *p != '\t') return false;
  return true;
}

static bool assistant_valid_id(const char *id, size_t capacity)
{
  if (!assistant_valid_text(id, capacity, false)) return false;
  for (const unsigned char *p = (const unsigned char *)id; *p; p++)
    if (!( (*p >= 'a' && *p <= 'z') || (*p >= 'A' && *p <= 'Z') ||
           (*p >= '0' && *p <= '9') || *p == '-' || *p == '_' ||
           *p == '.' || *p == ':' )) return false;
  return true;
}

static int assistant_load(struct disk_state_s *state)
{
  int ret;
#ifdef CONFIG_BUFFER_VELA_SOURCE_JOURNAL
  bool migrate=false;
  errno=0;cJSON *value=buffer_source_projection_read(ASSISTANT_JOURNAL_FILE,BUFFER_AGENT_JSON_BYTES);
  if(value){ret=assistant_decode(value,state);cJSON_Delete(value);}
  else {
    ret=-(errno?errno:EIO);if(ret!=-ENOENT)return ret;
    ret=assistant_load_legacy(state);migrate=true;
  }
#else
  ret=assistant_load_legacy(state);
#endif
  if(ret)return ret;
  if(state->operation_count<ASSISTANT_OP_HISTORY&&state->operation_next!=state->operation_count)return -EBADMSG;
  for(size_t i=0;i<state->timer_count;i++){
    const struct disk_timer_s *t=&state->timers[i];
    if(!assistant_valid_id(t->id,sizeof(t->id))||!assistant_valid_text(t->label,sizeof(t->label),false)||
       t->remaining_ms>t->duration_ms||t->wall_deadline_ms<0||t->sequence>state->next_sequence)return -EBADMSG;
    for(size_t j=0;j<i;j++)if(!strcmp(t->id,state->timers[j].id))return -EBADMSG;
  }
  for(size_t i=0;i<state->alarm_count;i++){
    const struct disk_alarm_s *a=&state->alarms[i];
    if(!assistant_valid_id(a->id,sizeof(a->id))||!assistant_valid_text(a->label,sizeof(a->label),false))return -EBADMSG;
    if(a->sequence>state->next_sequence)return -EBADMSG;
    for(size_t j=0;j<i;j++)if(!strcmp(a->id,state->alarms[j].id))return -EBADMSG;
  }
  for(size_t i=0;i<state->operation_count;i++){
    const struct disk_operation_s *o=&state->operations[i];
    if(!assistant_valid_id(o->operation_id,sizeof(o->operation_id))||
       (o->object_id[0]&&!assistant_valid_id(o->object_id,sizeof(o->object_id))))return -EBADMSG;
    if(o->sequence>state->next_sequence||o->remaining_ms>ASSISTANT_MAX_TIMER_MS||
       o->operation<BUFFER_ASSISTANT_TIMER_CREATE||o->operation>BUFFER_ASSISTANT_TIMER_RESTART||
       ((o->operation<=BUFFER_ASSISTANT_ALARM_CANCEL||o->operation==BUFFER_ASSISTANT_TIMER_RESTART)&&
        (!o->object_id[0]||o->state<BUFFER_ASSISTANT_RUNNING||o->state>BUFFER_ASSISTANT_CANCELLED))||
       ((o->operation==BUFFER_ASSISTANT_TRANSLATION_SHOW||o->operation==BUFFER_ASSISTANT_RECIPE_SHOW)&&o->state!=0))return -EBADMSG;
    for(size_t j=0;j<i;j++)if(!strcmp(o->operation_id,state->operations[j].operation_id))return -EBADMSG;
  }
#ifdef CONFIG_BUFFER_VELA_SOURCE_JOURNAL
  if(migrate){
    value=assistant_encode(state);if(!value)return -ENOMEM;
    ret=buffer_source_projection_legacy(ASSISTANT_JOURNAL_FILE,value);cJSON_Delete(value);
    if(ret)return ret;
  }
#endif
  return 0;
}

static uint64_t assistant_hash_bytes(uint64_t hash, const void *data,
                                    size_t length)
{
  const unsigned char *bytes = data;
  for (size_t i = 0; i < length; i++)
    {
      hash ^= bytes[i];
      hash *= 1099511628211ULL;
    }
  hash ^= 0xff;
  return hash * 1099511628211ULL;
}

static uint64_t assistant_hash_string(uint64_t hash, const char *value)
{
  return assistant_hash_bytes(hash, value, strlen(value));
}

static uint64_t assistant_fingerprint(const struct buffer_assistant_request_s *r)
{
  uint64_t hash = 1469598103934665603ULL;
  hash = assistant_hash_bytes(hash, &r->operation, sizeof(r->operation));
  switch (r->operation)
    {
      case BUFFER_ASSISTANT_TIMER_CREATE:
        hash = assistant_hash_string(hash, r->label);
        return assistant_hash_bytes(hash, &r->duration_ms, sizeof(r->duration_ms));
      case BUFFER_ASSISTANT_TIMER_PAUSE:
      case BUFFER_ASSISTANT_TIMER_RESUME:
      case BUFFER_ASSISTANT_TIMER_CANCEL:
      case BUFFER_ASSISTANT_TIMER_RESTART:
      case BUFFER_ASSISTANT_ALARM_CANCEL:
        return assistant_hash_string(hash, r->object_id);
      case BUFFER_ASSISTANT_ALARM_CREATE:
        hash = assistant_hash_string(hash, r->label);
        return assistant_hash_bytes(hash, &r->scheduled_at_unix_ms,
                                    sizeof(r->scheduled_at_unix_ms));
      case BUFFER_ASSISTANT_TRANSLATION_SHOW:
        hash = assistant_hash_string(hash, r->original);
        hash = assistant_hash_string(hash, r->translated);
        hash = assistant_hash_string(hash, r->source_language);
        return assistant_hash_string(hash, r->target_language);
      case BUFFER_ASSISTANT_RECIPE_SHOW:
        hash = assistant_hash_string(hash, r->recipe_title);
        hash = assistant_hash_string(hash, r->ingredients);
        if(r->image_id[0])hash = assistant_hash_string(hash, r->image_id);
        hash = assistant_hash_bytes(hash, &r->step_count, sizeof(r->step_count));
        for (size_t i = 0; i < r->step_count; i++)
          {
            hash = assistant_hash_string(hash, r->steps[i].title);
            hash = assistant_hash_string(hash, r->steps[i].detail);
            hash = assistant_hash_bytes(hash, &r->steps[i].timer_ms,
                                        sizeof(r->steps[i].timer_ms));
          }
        return hash;
      default:
        return hash;
    }
}

