int buffer_assistant_execute(const struct buffer_assistant_request_s *request,
                             struct buffer_assistant_result_s *result)
{
  struct buffer_assistant_result_s local_result;
  uint64_t fingerprint;
  int ret;

  if (result == NULL) result = &local_result;
  memset(result, 0, sizeof(*result));
  ret = assistant_validate_request(request);
  if (ret < 0) return ret;
  ret = buffer_assistant_init();
  if (ret < 0) return ret;
  fingerprint = assistant_fingerprint(request);

  pthread_mutex_lock(&g_lock);
  ret=assistant_reconcile_locked();
  if(ret){pthread_mutex_unlock(&g_lock);return ret;}
#ifdef CONFIG_BUFFER_VELA_SOURCE_JOURNAL
  ret=assistant_historical_operation(request,fingerprint,result);
  if(ret){pthread_mutex_unlock(&g_lock);return ret==1?0:ret;}
#else
  int existing = assistant_find_operation(&g_state, request->operation_id);
  if (existing >= 0)
    {
      const struct disk_operation_s *saved = &g_state.operations[existing];
      if (saved->fingerprint != fingerprint)
        {
          pthread_mutex_unlock(&g_lock);
          return -EALREADY;
        }
      result->duplicate = true;
      result->state = (enum buffer_assistant_state_e)saved->state;
      result->remaining_ms = saved->remaining_ms;
      snprintf(result->object_id, sizeof(result->object_id), "%s", saved->object_id);
      pthread_mutex_unlock(&g_lock);
      return 0;
    }

#endif
  if(request->operation==BUFFER_ASSISTANT_ALARM_CREATE){
    int64_t wall=assistant_wall_ms();
    if(wall<=0||wall>INT64_MAX-ASSISTANT_MAX_ALARM_AHEAD_MS||
       request->scheduled_at_unix_ms<wall+1000||request->scheduled_at_unix_ms>wall+ASSISTANT_MAX_ALARM_AHEAD_MS)
      {pthread_mutex_unlock(&g_lock);return -ERANGE;}
  }
  if(g_state.next_sequence>UINT64_MAX-3){pthread_mutex_unlock(&g_lock);return -EOVERFLOW;}

  if (request->operation == BUFFER_ASSISTANT_TRANSLATION_SHOW ||
      request->operation == BUFFER_ASSISTANT_RECIPE_SHOW)
    {
      g_rollback_state = g_state;
      g_work_state = g_state;
      assistant_record_operation(&g_work_state, request, fingerprint, result);
      ret = assistant_persist(&g_work_state,"AssistantDisplayRequested",request);
      if (ret == 0)
        {
          g_state = g_work_state;
          if (request->operation == BUFFER_ASSISTANT_TRANSLATION_SHOW)
            ret = buffer_a2ui_present_translation(request->operation_id,
            request->original, request->translated, request->source_language,
            request->target_language);
          else
            ret = buffer_a2ui_present_recipe_image(request->operation_id,
                request->recipe_title, request->ingredients, request->steps,
                request->step_count,request->image_id);
          if (ret < 0)
            {
              if (assistant_persist(&g_rollback_state,"AssistantDisplayFailed",request) == 0)
                g_state = g_rollback_state;
            }
        }
      pthread_mutex_unlock(&g_lock);
      return ret;
    }

  ret = assistant_execute_domain(request, result, fingerprint);
  pthread_mutex_unlock(&g_lock);
  if (ret < 0) return ret;
  if (request->operation == BUFFER_ASSISTANT_TIMER_CREATE ||
      request->operation == BUFFER_ASSISTANT_TIMER_PAUSE ||
      request->operation == BUFFER_ASSISTANT_TIMER_RESUME ||
      request->operation == BUFFER_ASSISTANT_TIMER_CANCEL ||
      request->operation == BUFFER_ASSISTANT_TIMER_RESTART)
    (void)buffer_a2ui_present_timer(result->object_id);
  else if (request->operation == BUFFER_ASSISTANT_ALARM_CREATE ||
           request->operation == BUFFER_ASSISTANT_ALARM_CANCEL)
    (void)buffer_a2ui_present_alarm(result->object_id);
  return 0;
}

int buffer_assistant_snapshot(enum buffer_assistant_event_e type,
                              struct buffer_assistant_item_s *items,
                              size_t capacity, size_t *count)
{
  if (count == NULL || (capacity > 0 && items == NULL) ||
      (type != BUFFER_ASSISTANT_EVENT_TIMER &&
       type != BUFFER_ASSISTANT_EVENT_ALARM)) return -EINVAL;
  *count = 0;
  int ret = buffer_assistant_init();
  if (ret < 0) return ret;
  pthread_mutex_lock(&g_lock);
  ret=assistant_reconcile_locked();if(ret){pthread_mutex_unlock(&g_lock);return ret;}
  size_t total = type == BUFFER_ASSISTANT_EVENT_TIMER ?
                 g_state.timer_count : g_state.alarm_count;
  size_t copied = total < capacity ? total : capacity;
  int64_t mono = assistant_monotonic_ms();
  for (size_t i = 0; i < copied; i++)
    assistant_fill_item(type, &g_state, i, mono, &items[i]);
  *count = total;
  pthread_mutex_unlock(&g_lock);
  return total > capacity ? -ENOSPC : 0;
}

int buffer_assistant_get(enum buffer_assistant_event_e type,
                         const char *object_id,
                         struct buffer_assistant_item_s *item)
{
  if (object_id == NULL || item == NULL ||
      !assistant_valid_id(object_id, BUFFER_ASSISTANT_ID_SIZE) ||
      (type != BUFFER_ASSISTANT_EVENT_TIMER &&
       type != BUFFER_ASSISTANT_EVENT_ALARM)) return -EINVAL;
  int ret = buffer_assistant_init();
  if (ret < 0) return ret;
  pthread_mutex_lock(&g_lock);
  ret=assistant_reconcile_locked();if(ret){pthread_mutex_unlock(&g_lock);return ret;}
  size_t total = type == BUFFER_ASSISTANT_EVENT_TIMER ?
                 g_state.timer_count : g_state.alarm_count;
  for (size_t i = 0; i < total; i++)
    {
      const char *id = type == BUFFER_ASSISTANT_EVENT_TIMER ?
                       g_state.timers[i].id : g_state.alarms[i].id;
      if (strcmp(id, object_id) == 0)
        {
          assistant_fill_item(type, &g_state, i, assistant_monotonic_ms(), item);
          pthread_mutex_unlock(&g_lock);
          return 0;
        }
    }
  pthread_mutex_unlock(&g_lock);
  return -ENOENT;
}

/* Presentation reads never initialize/reconcile storage or wait for a writer. */
int buffer_assistant_ui_snapshot(enum buffer_assistant_event_e type,
                                 struct buffer_assistant_item_s *items,
                                 size_t capacity, size_t *count)
{
  if (!count || (capacity && !items) ||
      (type != BUFFER_ASSISTANT_EVENT_TIMER && type != BUFFER_ASSISTANT_EVENT_ALARM)) return -EINVAL;
  if (pthread_mutex_trylock(&g_lock)) return -EAGAIN;
  size_t total = !g_initialized ? 0 : type == BUFFER_ASSISTANT_EVENT_TIMER ?
                 g_state.timer_count : g_state.alarm_count;
  size_t copied = total < capacity ? total : capacity;
  int64_t mono = assistant_monotonic_ms();
  for (size_t i = 0; i < copied; i++)
    assistant_fill_item(type, &g_state, i, mono, &items[i]);
  *count = total;
  pthread_mutex_unlock(&g_lock);
  return total > capacity ? -ENOSPC : 0;
}

int buffer_assistant_ui_get(enum buffer_assistant_event_e type, const char *object_id,
                            struct buffer_assistant_item_s *item)
{
  if (!object_id || !item ||
      (type != BUFFER_ASSISTANT_EVENT_TIMER && type != BUFFER_ASSISTANT_EVENT_ALARM)) return -EINVAL;
  if (pthread_mutex_trylock(&g_lock)) return -EAGAIN;
  size_t total = !g_initialized ? 0 : type == BUFFER_ASSISTANT_EVENT_TIMER ?
                 g_state.timer_count : g_state.alarm_count;
  for (size_t i = 0; i < total; i++)
    {
      const char *id = type == BUFFER_ASSISTANT_EVENT_TIMER ?
                       g_state.timers[i].id : g_state.alarms[i].id;
      if (!strcmp(id, object_id))
        {
          assistant_fill_item(type, &g_state, i, assistant_monotonic_ms(), item);
          pthread_mutex_unlock(&g_lock);
          return 0;
        }
    }
  pthread_mutex_unlock(&g_lock);
  return -ENOENT;
}

