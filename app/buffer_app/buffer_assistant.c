/* Portable semantic snapshots, not a dump of a C struct. uint64 values are
 * decimal strings so operation fingerprints and counters never lose bits in
 * cJSON's double representation or on a receiving architecture. */
static bool assistant_json_u64(cJSON *value,const char *key,uint64_t number)
{
  char text[21];snprintf(text,sizeof(text),"%llu",(unsigned long long)number);
  return cJSON_AddStringToObject(value,key,text)!=NULL;
}
static bool assistant_read_u64(const cJSON *value,const char *key,uint64_t max,uint64_t *out)
{
  const cJSON *item=cJSON_GetObjectItemCaseSensitive(value,key);
  if(!cJSON_IsString(item)||!item->valuestring[0])return false;
  const char *text=item->valuestring;uint64_t number=0;
  if(text[0]=='0'&&text[1])return false;
  for(;*text;text++){
    if(*text<'0'||*text>'9'||number>max/10||
       (number==max/10&&(uint64_t)(*text-'0')>max%10))return false;
    number=number*10+(unsigned)(*text-'0');
  }
  *out=number;return true;
}
static bool assistant_read_number(const cJSON *value,const char *key,uint32_t max,uint32_t *out)
{
  const cJSON *item=cJSON_GetObjectItemCaseSensitive(value,key);
  if(!cJSON_IsNumber(item)||!isfinite(item->valuedouble)||item->valuedouble<0||
     item->valuedouble>max||floor(item->valuedouble)!=item->valuedouble)return false;
  *out=(uint32_t)item->valuedouble;return true;
}
static bool assistant_read_text(const cJSON *value,const char *key,char *out,size_t size)
{
  const cJSON *item=cJSON_GetObjectItemCaseSensitive(value,key);
  if(!cJSON_IsString(item)||strlen(item->valuestring)>=size)return false;
  snprintf(out,size,"%s",item->valuestring);return true;
}
static cJSON *assistant_encode(const struct disk_state_s *state)
{
  cJSON *value=cJSON_CreateObject();if(!value)return NULL;
  cJSON *timers=cJSON_AddArrayToObject(value,"timers"),*alarms=cJSON_AddArrayToObject(value,"alarms");
  cJSON *operations=cJSON_AddArrayToObject(value,"operations");
  if(!timers||!alarms||!operations||!cJSON_AddNullToObject(value,"request")||!cJSON_AddNumberToObject(value,"schema_version",1)||
     !assistant_json_u64(value,"next_sequence",state->next_sequence)||
     !cJSON_AddNumberToObject(value,"operation_next",state->operation_next))goto fail;
  for(size_t i=0;i<state->timer_count;i++){
    const struct disk_timer_s *t=&state->timers[i];cJSON *item=cJSON_CreateObject();
    if (!item)
      goto fail;
    if (!cJSON_AddItemToArray(timers, item)) {
      cJSON_Delete(item);
      goto fail;
    }
    if(!cJSON_AddStringToObject(item,"id",t->id)||!cJSON_AddStringToObject(item,"label",t->label)||
       !cJSON_AddNumberToObject(item,"duration_ms",t->duration_ms)||!cJSON_AddNumberToObject(item,"remaining_ms",t->remaining_ms)||
       !assistant_json_u64(item,"wall_deadline_ms",(uint64_t)t->wall_deadline_ms)||
       !assistant_json_u64(item,"sequence",t->sequence)||!cJSON_AddNumberToObject(item,"state",t->state))goto fail;
    if(t->reserved[0]&&!cJSON_AddBoolToObject(item,"recipe_step",true))goto fail;
  }
  for(size_t i=0;i<state->alarm_count;i++){
    const struct disk_alarm_s *a=&state->alarms[i];cJSON *item=cJSON_CreateObject();
    if (!item)
      goto fail;
    if (!cJSON_AddItemToArray(alarms, item)) {
      cJSON_Delete(item);
      goto fail;
    }
    if(!cJSON_AddStringToObject(item,"id",a->id)||!cJSON_AddStringToObject(item,"label",a->label)||
       !assistant_json_u64(item,"scheduled_at_unix_ms",(uint64_t)a->scheduled_at_unix_ms)||
       !assistant_json_u64(item,"sequence",a->sequence)||!cJSON_AddNumberToObject(item,"state",a->state))goto fail;
  }
  for(size_t i=0;i<state->operation_count;i++){
    const struct disk_operation_s *o=&state->operations[i];cJSON *item=cJSON_CreateObject();
    if (!item)
      goto fail;
    if (!cJSON_AddItemToArray(operations, item)) {
      cJSON_Delete(item);
      goto fail;
    }
    if(!cJSON_AddStringToObject(item,"operation_id",o->operation_id)||!cJSON_AddStringToObject(item,"object_id",o->object_id)||
       !assistant_json_u64(item,"fingerprint",o->fingerprint)||!assistant_json_u64(item,"sequence",o->sequence)||
       !cJSON_AddNumberToObject(item,"remaining_ms",o->remaining_ms)||!cJSON_AddNumberToObject(item,"operation",o->operation)||
       !cJSON_AddNumberToObject(item,"state",o->state))goto fail;
  }
  return value;
fail:
  cJSON_Delete(value);return NULL;
}
static cJSON *assistant_encode_request(const struct buffer_assistant_request_s *r)
{
  cJSON *value=cJSON_CreateObject();if(!value)return NULL;
  if(!cJSON_AddNumberToObject(value,"operation",r->operation)||
     !cJSON_AddStringToObject(value,"operation_id",r->operation_id)||
     !assistant_json_u64(value,"fingerprint",assistant_fingerprint(r)))goto fail;
  switch(r->operation){
    case BUFFER_ASSISTANT_TIMER_PAUSE:
    case BUFFER_ASSISTANT_TIMER_RESUME:
    case BUFFER_ASSISTANT_TIMER_CANCEL:
      case BUFFER_ASSISTANT_TIMER_RESTART:
    case BUFFER_ASSISTANT_ALARM_CANCEL:
      if(!cJSON_AddStringToObject(value,"object_id",r->object_id))goto fail;
      break;
    case BUFFER_ASSISTANT_TIMER_CREATE:
      if(!cJSON_AddStringToObject(value,"label",r->label)||!cJSON_AddNumberToObject(value,"duration_ms",r->duration_ms))goto fail;
      break;
    case BUFFER_ASSISTANT_ALARM_CREATE:
      if(!cJSON_AddStringToObject(value,"label",r->label)||
         !assistant_json_u64(value,"scheduled_at_unix_ms",(uint64_t)r->scheduled_at_unix_ms))goto fail;
      break;
    case BUFFER_ASSISTANT_TRANSLATION_SHOW:
      if(!cJSON_AddStringToObject(value,"original",r->original)||!cJSON_AddStringToObject(value,"translated",r->translated)||
         !cJSON_AddStringToObject(value,"source_language",r->source_language)||!cJSON_AddStringToObject(value,"target_language",r->target_language))goto fail;
      break;
    case BUFFER_ASSISTANT_RECIPE_SHOW: {
      cJSON *steps=cJSON_AddArrayToObject(value,"steps");
      if(!steps||!cJSON_AddStringToObject(value,"title",r->recipe_title)||!cJSON_AddStringToObject(value,"ingredients",r->ingredients))goto fail;
      if(r->image_id[0]&&!cJSON_AddStringToObject(value,"image_id",r->image_id))goto fail;
      for(size_t i=0;i<r->step_count;i++){
        cJSON *step=cJSON_CreateObject();if(!step)goto fail;
        if(!cJSON_AddItemToArray(steps,step)){cJSON_Delete(step);goto fail;}
        if(!cJSON_AddStringToObject(step,"title",r->steps[i].title)||!cJSON_AddStringToObject(step,"detail",r->steps[i].detail)||
           !cJSON_AddNumberToObject(step,"timer_ms",r->steps[i].timer_ms))goto fail;
      }
      break;
    }
    default:break;
  }
  return value;
fail:
  cJSON_Delete(value);return NULL;
}
static int assistant_decode(const cJSON *value,struct disk_state_s *state)
{
  uint32_t number=0;uint64_t wide=0;
  const cJSON *timers=cJSON_GetObjectItemCaseSensitive(value,"timers"),*alarms=cJSON_GetObjectItemCaseSensitive(value,"alarms");
  const cJSON *operations=cJSON_GetObjectItemCaseSensitive(value,"operations");
  const cJSON *request=cJSON_GetObjectItemCaseSensitive(value,"request");
  memset(state,0,sizeof(*state));
  if(!cJSON_IsObject(value)||cJSON_GetArraySize(value)!=7||(!cJSON_IsNull(request)&&!cJSON_IsObject(request))||
     !assistant_read_number(value,"schema_version",1,&number)||number!=1||
     !assistant_read_u64(value,"next_sequence",UINT64_MAX,&state->next_sequence)||
     !assistant_read_number(value,"operation_next",ASSISTANT_OP_HISTORY-1,&number)||
     !cJSON_IsArray(timers)||cJSON_GetArraySize(timers)>BUFFER_ASSISTANT_MAX_TIMERS||
     !cJSON_IsArray(alarms)||cJSON_GetArraySize(alarms)>BUFFER_ASSISTANT_MAX_ALARMS||
     !cJSON_IsArray(operations)||cJSON_GetArraySize(operations)>ASSISTANT_OP_HISTORY)return -EBADMSG;
  state->operation_next=(uint8_t)number;
  state->timer_count=(uint8_t)cJSON_GetArraySize(timers);state->alarm_count=(uint8_t)cJSON_GetArraySize(alarms);
  state->operation_count=(uint8_t)cJSON_GetArraySize(operations);
  if(state->operation_count<ASSISTANT_OP_HISTORY&&state->operation_next!=state->operation_count)return -EBADMSG;
  for(size_t i=0;i<state->timer_count;i++){
    const cJSON *item=cJSON_GetArrayItem(timers,(int)i);struct disk_timer_s *t=&state->timers[i];
    const cJSON *recipe=cJSON_GetObjectItemCaseSensitive(item,"recipe_step");
    if(!cJSON_IsObject(item)||cJSON_GetArraySize(item)!=(recipe?8:7)||(recipe&&!cJSON_IsBool(recipe))||!assistant_read_text(item,"id",t->id,sizeof(t->id))||
       !assistant_read_text(item,"label",t->label,sizeof(t->label))||
       !assistant_read_number(item,"duration_ms",ASSISTANT_MAX_TIMER_MS,&t->duration_ms)||!t->duration_ms||
       !assistant_read_number(item,"remaining_ms",t->duration_ms,&t->remaining_ms)||
       !assistant_read_u64(item,"wall_deadline_ms",INT64_MAX,&wide))return -EBADMSG;
    t->wall_deadline_ms=(int64_t)wide;
    if(!assistant_read_u64(item,"sequence",state->next_sequence,&t->sequence)||
       !assistant_read_number(item,"state",BUFFER_ASSISTANT_CANCELLED,&number)||number<BUFFER_ASSISTANT_RUNNING)return -EBADMSG;
    t->state=(uint8_t)number;
    t->reserved[0]=cJSON_IsTrue(recipe);
    for(size_t j=0;j<i;j++)if(!strcmp(state->timers[j].id,t->id))return -EBADMSG;
  }
  for(size_t i=0;i<state->alarm_count;i++){
    const cJSON *item=cJSON_GetArrayItem(alarms,(int)i);struct disk_alarm_s *a=&state->alarms[i];
    if(!cJSON_IsObject(item)||cJSON_GetArraySize(item)!=5||!assistant_read_text(item,"id",a->id,sizeof(a->id))||
       !assistant_read_text(item,"label",a->label,sizeof(a->label))||
       !assistant_read_u64(item,"scheduled_at_unix_ms",INT64_MAX,&wide)||!wide)return -EBADMSG;
    a->scheduled_at_unix_ms=(int64_t)wide;
    if(!assistant_read_u64(item,"sequence",state->next_sequence,&a->sequence)||
       !assistant_read_number(item,"state",BUFFER_ASSISTANT_CANCELLED,&number)||number<BUFFER_ASSISTANT_RUNNING)return -EBADMSG;
    a->state=(uint8_t)number;
    for(size_t j=0;j<i;j++)if(!strcmp(state->alarms[j].id,a->id))return -EBADMSG;
  }
  for(size_t i=0;i<state->operation_count;i++){
    const cJSON *item=cJSON_GetArrayItem(operations,(int)i);struct disk_operation_s *o=&state->operations[i];
    if(!cJSON_IsObject(item)||cJSON_GetArraySize(item)!=7||
       !assistant_read_text(item,"operation_id",o->operation_id,sizeof(o->operation_id))||
       !assistant_read_text(item,"object_id",o->object_id,sizeof(o->object_id))||
       !assistant_read_u64(item,"fingerprint",UINT64_MAX,&o->fingerprint)||
       !assistant_read_u64(item,"sequence",state->next_sequence,&o->sequence)||
       !assistant_read_number(item,"remaining_ms",ASSISTANT_MAX_TIMER_MS,&o->remaining_ms)||
       !assistant_read_number(item,"operation",BUFFER_ASSISTANT_TIMER_RESTART,&number)||!number)return -EBADMSG;
    o->operation=(uint8_t)number;
    if(!assistant_read_number(item,"state",BUFFER_ASSISTANT_CANCELLED,&number))return -EBADMSG;
    o->state=(uint8_t)number;
    for(size_t j=0;j<i;j++)if(!strcmp(state->operations[j].operation_id,o->operation_id))return -EBADMSG;
    if(o->operation==BUFFER_ASSISTANT_TIMER_CREATE&&assistant_recipe_timer_key(o->operation_id))
      for(size_t j=0;j<state->timer_count;j++)if(!strcmp(state->timers[j].id,o->object_id))state->timers[j].reserved[0]=1;
  }
  state->magic=ASSISTANT_DISK_MAGIC;state->version=ASSISTANT_DISK_VERSION;state->bytes=sizeof(*state);
  state->checksum=assistant_crc32((const unsigned char *)state,sizeof(*state));
  return 0;
}
