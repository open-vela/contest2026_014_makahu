/* Recipe timer identities are generated by both local and declared A2UI
 * recipe steps. Persist the ownership in a reserved byte, preserving the
 * deployed binary timer/state layout and existing request fingerprints. */
static bool assistant_recipe_timer_key(const char *id)
{
  size_t n=strlen(id);if((n!=23&&n!=25)||strncmp(id,"recipe-",7))return false;
  for(unsigned i=7;i<23;i++)if(!((id[i]>='0'&&id[i]<='9')||(id[i]>='a'&&id[i]<='f')))return false;
  return n==23||(id[23]=='-'&&id[24]>='1'&&id[24]<='9');
}

